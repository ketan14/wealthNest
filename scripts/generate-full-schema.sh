#!/usr/bin/env bash
# ==============================================================================
# Regenerates supabase/full_schema.sql as an ordered, reproducible concatenation
# of every versioned migration in supabase/migrations/.
#
# full_schema.sql is a REFERENCE / FRESH-PROJECT PROVISIONING SNAPSHOT only:
#   * The source of truth remains supabase/migrations/ (applied via `supabase db push`).
#   * Never apply full_schema.sql to a database that already has migrations recorded
#     in supabase_migrations.schema_migrations.
#   * supabase/seed_qa.sql is intentionally EXCLUDED (QA-only fixtures).
#
# Usage:
#   ./scripts/generate-full-schema.sh          # regenerate snapshot
#   ./scripts/generate-full-schema.sh --check  # exit 1 if snapshot is stale (CI-friendly)
# ==============================================================================
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MIGRATIONS_DIR="$ROOT_DIR/supabase/migrations"
OUTPUT_FILE="$ROOT_DIR/supabase/full_schema.sql"

shopt -s nullglob
migrations=("$MIGRATIONS_DIR"/*.sql)
shopt -u nullglob

if [ "${#migrations[@]}" -eq 0 ]; then
  echo "No migrations found in $MIGRATIONS_DIR" >&2
  exit 1
fi

# Deterministic lexical (timestamp) ordering
IFS=$'\n' migrations=($(printf '%s\n' "${migrations[@]}" | LC_ALL=C sort))
unset IFS

first_version="$(basename "${migrations[0]}" | cut -d_ -f1)"
last_version="$(basename "${migrations[-1]}" | cut -d_ -f1)"

render() {
  cat <<EOF
-- ==============================================================================
-- WealthNest — Full Schema Provisioning Snapshot (GENERATED FILE — DO NOT EDIT)
-- ==============================================================================
-- Generated by: scripts/generate-full-schema.sh
-- Source:       supabase/migrations/ (${#migrations[@]} files, ${first_version} → ${last_version})
--
-- Purpose:
--   Reference snapshot of the complete WealthNest PostgreSQL schema (tables,
--   household_id tenancy, visibility/privacy columns, joint ownership,
--   invitations, RLS policies, SECURITY DEFINER helpers, RPCs, Storage policies,
--   and least-privilege grants) for code review and fresh-project bootstrap.
--
-- Rules:
--   * supabase/migrations/ is the source of truth; deploy with `supabase db push`.
--   * Apply this file ONLY to a brand-new Supabase project with zero recorded
--     migrations (it requires Supabase-managed auth.* and storage.* schemas).
--   * supabase/seed_qa.sql is intentionally excluded (QA-only fixtures; never Production).
--   * Regenerate after adding any migration: ./scripts/generate-full-schema.sh
-- ==============================================================================

EOF

  for file in "${migrations[@]}"; do
    name="$(basename "$file")"
    printf '\n-- >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>\n'
    printf -- '-- BEGIN MIGRATION: %s\n' "$name"
    printf -- '-- >>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>>\n\n'
    # Normalise CRLF to LF and guarantee a trailing newline per migration
    sed 's/\r$//' "$file"
    [ -n "$(tail -c1 "$file")" ] && printf '\n'
    printf -- '\n-- END MIGRATION: %s\n' "$name"
  done
}

if [ "${1:-}" = "--check" ]; then
  if diff -q <(render) "$OUTPUT_FILE" >/dev/null 2>&1; then
    echo "full_schema.sql is up to date (${first_version} → ${last_version})."
    exit 0
  fi
  echo "full_schema.sql is STALE. Run ./scripts/generate-full-schema.sh and commit the result." >&2
  exit 1
fi

render > "$OUTPUT_FILE"
echo "Wrote $OUTPUT_FILE from ${#migrations[@]} migrations (${first_version} → ${last_version})."
